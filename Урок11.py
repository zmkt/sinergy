import collections


# Задание №1

def факториал(число):
    результат = 1
    for множитель in range(2, число + 1):
        результат *= множитель
    return результат


n = int(input("Введите натуральное число: "))
f = факториал(n)

print("Факториал числа", n, "равен", f)

список = []
for число in range(f, 0, -1):
    список.append(факториал(число))

print(список)


# Задание №2

pets = {
    1: {
        "Мухтар": {
            "Вид питомца": "Собака",
            "Возраст питомца": 9,
            "Имя владельца": "Павел",
        },
    },
    2: {
        "Каа": {
            "Вид питомца": "желторотый питон",
            "Возраст питомца": 19,
            "Имя владельца": "Саша",
        },
    },
}


def get_pet(ID):
    # запись о питомце или False, если такого ID нет
    return pets[ID] if ID in pets.keys() else False


def get_suffix(age):
    # 11-14 — исключение, всегда "лет"
    последние_две = age % 100
    последняя = age % 10

    if 11 <= последние_две <= 14:
        return "лет"
    if последняя == 1:
        return "год"
    if 2 <= последняя <= 4:
        return "года"
    return "лет"


def описание(ID):
    # собирает предложение о питомце, ID уже проверен вызывающей стороной
    запись = pets[ID]
    кличка = list(запись.keys())[0]
    данные = запись[кличка]

    возраст = данные["Возраст питомца"]

    return ('Это ' + данные["Вид питомца"] + ' по кличке "' + кличка + '". '
            + 'Возраст питомца: ' + str(возраст) + ' ' + get_suffix(возраст) + '. '
            + 'Имя владельца: ' + данные["Имя владельца"])


def pets_list():
    if len(pets) == 0:
        print("База данных пуста")
        return

    for ID in pets:
        print(ID, "-", описание(ID))


def create():
    if len(pets) == 0:
        новый_ID = 1
    else:
        last = collections.deque(pets, maxlen=1)[0]
        новый_ID = last + 1

    кличка = input("Кличка питомца: ")
    вид = input("Вид питомца: ")
    возраст = int(input("Возраст питомца: "))
    владелец = input("Имя владельца: ")

    pets[новый_ID] = {
        кличка: {
            "Вид питомца": вид,
            "Возраст питомца": возраст,
            "Имя владельца": владелец,
        },
    }

    print("Запись добавлена, ID:", новый_ID)


def read():
    ID = int(input("ID питомца: "))

    if get_pet(ID) == False:
        print("Питомца с таким ID нет")
        return

    print(описание(ID))


def update():
    ID = int(input("ID питомца: "))
    запись = get_pet(ID)

    if запись == False:
        print("Питомца с таким ID нет")
        return

    старая_кличка = list(запись.keys())[0]
    данные = запись[старая_кличка]

    print("Оставьте поле пустым, чтобы не менять его")

    кличка = input("Кличка (" + старая_кличка + "): ")
    вид = input("Вид (" + данные["Вид питомца"] + "): ")
    возраст = input("Возраст (" + str(данные["Возраст питомца"]) + "): ")
    владелец = input("Владелец (" + данные["Имя владельца"] + "): ")

    if кличка == "":
        кличка = старая_кличка
    if вид == "":
        вид = данные["Вид питомца"]
    if возраст == "":
        возраст = данные["Возраст питомца"]
    else:
        возраст = int(возраст)
    if владелец == "":
        владелец = данные["Имя владельца"]

    pets[ID] = {
        кличка: {
            "Вид питомца": вид,
            "Возраст питомца": возраст,
            "Имя владельца": владелец,
        },
    }

    print("Запись обновлена")


def delete():
    ID = int(input("ID питомца: "))

    if get_pet(ID) == False:
        print("Питомца с таким ID нет")
        return

    del pets[ID]
    print("Запись удалена")


print()
print("Команды: create, read, update, delete, list, stop")

command = ""
while command != "stop":
    command = input("Введите команду: ")

    if command == "create":
        create()
    elif command == "read":
        read()
    elif command == "update":
        update()
    elif command == "delete":
        delete()
    elif command == "list":
        pets_list()
    elif command != "stop":
        print("Неизвестная команда")

print("Работа завершена")
