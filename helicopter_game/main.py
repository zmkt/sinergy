import config
import storage
from game import Game


ЗАСТАВКА = """
==========================================
   ПОЖАРНЫЙ ВЕРТОЛЁТ — консольная игра
==========================================
Лес растёт и горит. Набирайте воду над рекой,
тушите деревья, покупайте улучшения в магазине
и жизни в госпитале. Берегитесь гроз.
"""


def спросить_число(вопрос, минимум, максимум, по_умолчанию):
    """Ввод числа с проверкой границ и значением по умолчанию."""
    ответ = input(вопрос + " [" + str(по_умолчанию) + "]: ").strip()

    if ответ == "":
        return по_умолчанию

    if not ответ.isdigit():
        print("Нужно целое число")
        return спросить_число(вопрос, минимум, максимум, по_умолчанию)

    число = int(ответ)
    if число < минимум or число > максимум:
        print("Допустимо от " + str(минимум) + " до " + str(максимум))
        return спросить_число(вопрос, минимум, максимум, по_умолчанию)

    return число


def выбрать_отрисовку():
    ответ = input("Рисовать эмодзи? (д/н) [д]: ").strip().lower()
    config.USE_EMOJI = ответ not in ("н", "n", "нет", "no")


def новая_игра():
    ширина = спросить_число("Ширина поля", 5, 40, 20)
    высота = спросить_число("Высота поля", 5, 20, 10)
    выбрать_отрисовку()

    Game.new_game(ширина, высота).run()


def загрузить_игру():
    if not storage.has_save():
        print("Файл сохранения не найден")
        return

    выбрать_отрисовку()
    поле, вертолёт, погода, тик = storage.load_game()
    Game(поле, вертолёт, погода, тик).run()


def main():
    print(ЗАСТАВКА)

    while True:
        print("1 — новая игра")
        print("2 — продолжить сохранённую")
        print("3 — выход")

        выбор = input("Выберите пункт: ").strip()

        if выбор == "1":
            новая_игра()
            return
        if выбор == "2":
            загрузить_игру()
            return
        if выбор == "3":
            print("До встречи!")
            return

        print("Такого пункта нет")


if __name__ == "__main__":
    main()
