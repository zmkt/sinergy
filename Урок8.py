# Задание №3 — минимальное количество лодок

print()
m = int(input("Грузоподъёмность лодки: "))
n = int(input("Количество рыбаков: "))

веса = []
for i in range(n):
    веса.append(int(input()))

веса.sort()

лодок = 0
слева = 0
справа = n - 1

while слева <= справа:
    # самого лёгкого сажаем к самому тяжёлому, если лодка выдержит
    if слева < справа and веса[слева] + веса[справа] <= m:
        слева += 1
    справа -= 1
    лодок += 1

print(лодок)
