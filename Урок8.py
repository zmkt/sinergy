# Задание №1 — перевернуть массив

N = int(input("Сколько будет чисел: "))

массив = []
for i in range(N):
    массив.append(int(input()))

массив.reverse()

print(*массив)


# Задание №2 — сдвинуть массив вправо на одну позицию

def сдвинуть(числа):
    последний = числа.pop()      # снимаем последний элемент
    числа.insert(0, последний)   # и ставим его в начало
    return числа


